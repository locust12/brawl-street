// ===== item art: ONE baked studio render per item, and ONE component that shows it =====
//
// Duane, 2026-10-14: *"na the icons look cheap as fuck still"*, then, after seeing the teardown of
// eight current shops: *"make it like counterstrike / fortnight. make them realistic and super
// detailed"*.
//
// What was here before was a 2px stroke with `fill: none` inside a hex plate. Across Fortnite, CS2,
// Apex, Overwatch, Deadlock, Brawlhalla and the Steam market, the same three things hold and that
// version broke all three:
//   1. the art is FILLED and lit, never an outline. A wireframe reads as a placeholder.
//   2. the art FILLS the tile. The old plate ate ~60% of the box.
//   3. rarity is a FIELD behind the art, not a tint on the line, or a Legendary and a Common are the
//      same drawing twice.
//
// So each item is real geometry with real materials (dev/itemforge/models.js), lit by a studio rig
// with an environment map and baked to a PNG (dev/itemforge/bake.mjs), then framed on its own alpha
// bounding box and shipped as webp (dev/itemforge/towebp.py). That is literally how Apex and CS2
// make their store art. To change one, edit the model and re-run:
//   node dev/itemforge/bake.mjs && python3 dev/itemforge/towebp.py
//
// 2026-10-15: TWO FAULTS FIXED HERE.
//
// 1. **The gear art existed and nothing could load it.** `towebp.py` splits the bake by the `g_`
//    prefix and writes the 29 locker pieces to `assets/gear/`, but `src()` hard-coded
//    `assets/items/` and `BAKED` listed weapons only. So `has('g_tape')` was false everywhere,
//    every locker card fell through to its emoji, and anything that did build a path 404'd.
//    The id prefix now picks the directory, and the two sets are listed separately.
// 2. **One component, every screen.** The marketplace, the locker, the inventory, the slot strip and
//    the item sheet each framed the art their own way, which is how `.ic` ended up with two
//    conflicting height rules and a 640x640 render laid out in a 212x132 box. `ItemArt.tile()`
//    returns the whole framed tile — rarity field, art, lock state, serial — and every screen uses
//    it, so a framing fix lands in all of them at once.
const ItemArt = (() => {
  // kept in step with assets/items/ by dev/itemforge/bake.mjs
  const WEAPONS = new Set(['aegis', 'ak', 'bat', 'blaster', 'bolt', 'boots', 'bow', 'buzzsaw', 'chain', 'deagle', 'fireaxe', 'flamer', 'freeze', 'gloves', 'manhole', 'medkit', 'mine', 'nailgun', 'pipebomb', 'pipegun', 'rebar', 'sweeper', 'thunder', 'turret', 'well', 'wreck', 'zip']);
  // kept in step with assets/gear/ by the same bake; `towebp.py` routes everything `g_*` here
  const GEAR = new Set(['g_aviators', 'g_backcap', 'g_band', 'g_bandana', 'g_beanie', 'g_boiler', 'g_boombox', 'g_bowtie', 'g_boxing', 'g_bucket', 'g_bull', 'g_bullion', 'g_cans', 'g_cape', 'g_cardoor', 'g_cellar', 'g_chain', 'g_chrome', 'g_cowboy', 'g_crate', 'g_crown', 'g_desk', 'g_dice', 'g_dish', 'g_driver', 'g_dumpster', 'g_fedora', 'g_firedoor', 'g_gaunt', 'g_goggles', 'g_golds', 'g_grill', 'g_gymlocker', 'g_halo', 'g_hitops', 'g_horns', 'g_hubcap', 'g_hydrant', 'g_ice', 'g_jukebox', 'g_kabuto', 'g_katana', 'g_key', 'g_knuck', 'g_latex', 'g_lighter', 'g_mafia', 'g_manhole', 'g_mitts', 'g_monocle', 'g_moto', 'g_ninja', 'g_oildrum', 'g_pack', 'g_padlock', 'g_pager', 'g_pallet', 'g_patch', 'g_pendant', 'g_pilot', 'g_pizzapan', 'g_plane', 'g_plank', 'g_plyboard', 'g_rayban', 'g_rings', 'g_riot', 'g_salt', 'g_sash', 'g_scarf', 'g_score', 'g_screens', 'g_shades', 'g_shutter', 'g_sign', 'g_sliders', 'g_snapback', 'g_sneaker', 'g_steels', 'g_stopsign', 'g_table', 'g_tags', 'g_tape', 'g_ticker', 'g_token', 'g_tooth', 'g_tophat', 'g_trucker', 'g_turnstile', 'g_vault', 'g_visor', 'g_watch', 'g_wheelrim', 'g_wings', 'g_work', 'g_wreath']);

  // 15 Oct: this list is now generated from `assets/cosm/*.webp` rather than typed. It held the
  // original 25 ids, so the 28 cosmetics added after it — every taunt, every title and 8 of the 12
  // KO effects — failed `has()`, fell through to the live `Cosm.swatch` fallback, and rendered as a
  // picture of the doge on the shop card. The bake and this list have to be regenerated together.
  //
  // and the cosmetic previews, baked by dev/cosmbake.mjs into assets/cosm/.
  // These used to be a live <canvas> painted at card-build time, which failed three ways at once
  // (a 54px corner chip instead of the art box, a repaint that never came when the portrait loaded
  // late, and a canvas layer that did not composite at all). Weapons already proved the reliable
  // path -- bake it once, ship a flat image -- so cosmetics now take it too.
// 'deagle' WAS IN THIS LIST and it is a WEAPON, not a cosmetic. `assets/cosm/deagle.webp` is an
// orphan — no entry in Econ.CAT.cosmetics has that id — but this list is generated by globbing
// `assets/cosm/*.webp`, so the stray file swept itself in, and `dir()` tests COSM first. The Desert
// Eagle's store card therefore loaded the dark, unlit cosmetic render instead of its own baked art,
// which is why re-baking assets/items/deagle.webp never fixed the card. Every other id here carries
// a cosmetic prefix (aur_/fin_/ko_/plt_/tnt_/trl_/ttl_/vic_); a bare weapon id never belongs.
const COSM = new Set(['aur_ember', 'aur_frost', 'aur_rain', 'aur_void', 'aur_volt', 'fin_carbon', 'fin_chrome', 'fin_gold', 'fin_rekt', 'fin_toxic', 'fin_vapor', 'ko_bell', 'ko_cash', 'ko_chalk', 'ko_conf', 'ko_drop', 'ko_lamp', 'ko_liq', 'ko_nova', 'ko_rain', 'ko_siren', 'ko_smoke', 'ko_spark', 'plt_degen', 'plt_found', 'plt_whale', 'tnt_bow', 'tnt_clap', 'tnt_flex', 'tnt_guard', 'tnt_hang', 'tnt_point', 'tnt_roll', 'tnt_shrug', 'tnt_spin', 'tnt_stomp', 'tnt_sweep', 'tnt_wave', 'trl_glitch', 'trl_gold', 'trl_ice', 'trl_neon', 'ttl_bellringer', 'ttl_blockcapt', 'ttl_closer', 'ttl_floor', 'ttl_houseedge', 'ttl_landlord', 'ttl_nightshift', 'ttl_regular', 'vic_diamond', 'vic_flex', 'vic_throne']);

  // .webp, not the .png master: 1.76 MB of PNG becomes ~18 KB of webp per item. The PNGs stay in
  // the repo as the masters the bake writes. The 640px render is a 3.2x supersample of the ~132px
  // tile and the downsample IS the anti-aliasing, so do not ship a smaller one.
  // WEAPONS wins over COSM: a weapon's art lives in assets/items/ and nothing in the cosmetics
  // folder may override it, however that folder was globbed. See the note on COSM above.
  const dir = id => (WEAPONS.has(id) ? 'assets/items/' : COSM.has(id) ? 'assets/cosm/' : id.slice(0, 2) === 'g_' ? 'assets/gear/' : 'assets/items/');
  const src = id => dir(id) + id + '.webp';
  const has = id => !!id && (WEAPONS.has(id) || GEAR.has(id) || COSM.has(id));

  // `colour` is the rarity colour. It is NOT applied to the art -- the art keeps its own materials,
  // exactly as a rendered object should, and the caller paints the rarity behind it. The argument
  // stays so older callers do not break.
  function html(id, colour, size) {
    const s = size || 64;
    if (!has(id)) return '';
    // NOT loading="lazy". 15 Oct: that one attribute is why the whole shop looked black. These tiles
    // live inside a scrolling modal, and the browser never decided the deferred ones were near enough
    // to fetch -- `naturalWidth` stayed 0 and every card fell back to its dark empty field. The same
    // attribute blanked 54 images on the marketplace page. A tile is ~7 KB; there is nothing to defer.
    //
    // `fetchpriority="high"` is the other half of the same bug, and it was the bigger half. 15 Oct,
    // measured against the deployed build: the title screen fires **86 images** (every fighter
    // cut-out) in the first second. An <img> is born at priority **Low**, so the 21 store renders
    // queued behind all of them -- requested at t+1.6s, not answered until **t+18.8s to t+22.4s**.
    // The player opens the Store and looks at 21 empty boxes for twenty seconds, which is exactly
    // what a broken shop looks like. Nothing 404'd, nothing threw; it was pure queue order.
    // High priority jumps the roster queue and HTTP/2 re-prioritises the ones already in flight.
    return `<img class="ia" src="${src(id)}" width="${s}" height="${s}" alt="" decoding="async" fetchpriority="high">`;
  }

  // ---- the one tile every screen uses -------------------------------------------------------
  // o: { id, icon, col, locked, unusual, serial, mint, ko, plus, size, label }
  //
  // `locked` dims the FIELD and stamps a padlock. It does NOT touch the art. The old shop crushed
  // every unowned item with `filter:brightness(0)` to a black silhouette, which is why Duane saw a
  // shop full of black squares: with payments off almost nothing is owned, so almost every card was
  // blacked out. No shop worth copying hides the item it is trying to sell you -- CS2, Fortnite and
  // Ronin all show the object at full brightness and put the price next to it.
  function tile(o) {
    o = o || {};
    const col = o.col || '#8fa3b0';
    const art = has(o.id) ? html(o.id, col, o.size || 128)
      : `<span class="ia-fb">${o.icon || '◆'}</span>`;
    const bits = [];
    if (o.unusual) bits.push(`<i class="ia-un" style="--uc:${o.unusual.color || '#ff6a2a'}">${o.unusual.name || 'Unusual'}</i>`);
    if (o.plus > 0) bits.push(`<i class="ia-plus">+${o.plus}</i>`);
    if (o.serial) bits.push(`<i class="ia-ser">#${o.serial}${o.mint ? '/' + o.mint : ''}</i>`);
    if (o.ko > 0) bits.push(`<i class="ia-ko">${o.ko} KO</i>`);
    return `<div class="ia-tile${o.locked ? ' ia-lock' : ''}${o.unusual ? ' ia-unu' : ''}" style="--rc:${col}">`
      + `<div class="ia-field"></div>${art}`
      + (o.locked ? '<i class="ia-pad">\u{1F512}</i>' : '')
      + (bits.length ? `<div class="ia-stamps">${bits.join('')}</div>` : '')
      + '</div>';
  }

  // The tile's own CSS, injected once, so no screen has to carry a copy of it. Every screen that
  // calls tile() gets the same framing, the same rarity field and the same stamps.
  const CSS = `
  .ia-tile{position:relative;display:grid;place-items:center;width:100%;height:132px;border-radius:10px;overflow:hidden;isolation:isolate}
  /* THE RARITY FIELD. Fortnite puts rarity BEHIND the object as a vertical gradient, dark at the top
     and saturated at the bottom, with the object lit on top of it. Recolouring the drawing itself
     makes every tier the same picture in a different tint. */
  .ia-tile .ia-field{position:absolute;inset:0;z-index:0;
    background:linear-gradient(170deg,
      color-mix(in srgb,var(--rc,#8fa3b0) 8%,#0b0d11) 0%,
      color-mix(in srgb,var(--rc,#8fa3b0) 26%,#0b0d11) 62%,
      color-mix(in srgb,var(--rc,#8fa3b0) 46%,#0b0d11) 100%)}
  /* a soft pool of shadow under the object so it sits on the card instead of floating */
  .ia-tile .ia-field::after{content:"";position:absolute;left:12%;right:12%;bottom:6px;height:16px;border-radius:50%;
    background:radial-gradient(50% 50% at 50% 50%,rgba(0,0,0,.55),transparent 70%)}
  /* inset:0 + object-fit:contain. The old rule was position:relative;height:100% inside a box with
     no definite height, so a 640x640 render laid out 212x212 in a 212x132 slot and lost 80px off
     the top and bottom. */
  .ia-tile .ia{position:absolute;inset:7px;z-index:1;width:auto;height:auto;max-width:calc(100% - 14px);max-height:calc(100% - 14px);
    margin:auto;object-fit:contain;display:block;filter:drop-shadow(0 6px 10px rgba(0,0,0,.45));transition:transform .18s ease}
  .ia-tile .ia-fb{position:relative;z-index:1;font-size:40px;line-height:1;filter:drop-shadow(0 3px 7px rgba(0,0,0,.6))}
  .card:hover .ia-tile .ia,.ia-hot:hover .ia{transform:scale(1.06)}
  @media (prefers-reduced-motion:reduce){.ia-tile .ia{transition:none}.card:hover .ia-tile .ia{transform:none}}
  /* LOCKED dims the field and stamps a padlock. The art stays lit: you are being sold this. */
  .ia-tile.ia-lock .ia-field{filter:saturate(.35) brightness(.62)}
  .ia-tile.ia-lock .ia{opacity:.9}
  .ia-tile .ia-pad{position:absolute;right:7px;top:6px;z-index:3;font-size:14px;font-style:normal;opacity:.82;
    filter:drop-shadow(0 1px 2px rgba(0,0,0,.9))}
  /* an Unusual is the whole reason a common hat can be worth anything, so it gets a lit rim */
  .ia-tile.ia-unu{box-shadow:inset 0 0 0 1px color-mix(in srgb,var(--uc,#ff6a2a) 60%,transparent),0 0 20px -6px var(--uc,#ff6a2a)}
  .ia-tile .ia-stamps{position:absolute;left:6px;bottom:6px;right:6px;z-index:3;display:flex;flex-wrap:wrap;gap:4px;align-items:flex-end}
  .ia-tile .ia-stamps i{font:800 8.5px var(--mono,monospace);font-style:normal;letter-spacing:.1em;text-transform:uppercase;
    padding:2px 5px;border-radius:3px;background:rgba(4,6,10,.78);color:#cfd6e4;box-shadow:inset 0 0 0 1px rgba(255,255,255,.12)}
  .ia-tile .ia-un{color:#0a0d12 !important;background:var(--uc,#ff6a2a) !important;box-shadow:none !important}
  .ia-tile .ia-plus{color:#ffd36a !important;box-shadow:inset 0 0 0 1px rgba(255,200,61,.5) !important}
  .ia-tile .ia-ko{color:#9fe8ff !important}
  `;
  let cssIn = false;
  function styles() {
    if (cssIn || typeof document === 'undefined') return;
    cssIn = true;
    const s = document.createElement('style'); s.id = 'iaCss'; s.textContent = CSS;
    document.head.appendChild(s);
  }

  return {
    html,
    svg: html,                      // old name, same job, so nothing that still calls svg() breaks
    src, dir, tile, styles, CSS,
    has,
    ids: () => [...WEAPONS, ...GEAR],
    isGear: id => GEAR.has(id),
  };
})();
if (typeof window !== 'undefined') window.ItemArt = ItemArt;
