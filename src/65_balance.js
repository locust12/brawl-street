// ===== per-fighter balance: reach levelling, weapon limits, chain-stun cap =====
//
// Everything here is OFF in seeded fights. The gate is `Game.sigs` (false whenever Game.start got a
// seed), so the bet arena (ARENA.version 1) and online replays are byte-identical: prove with
//   ~/.local/bin/node arena/test/det_node.js
// Nothing in this file uses Math.random or the DOM; the only inputs are fight state and frame counts.
//
// It installs itself by wrapping three methods instead of editing them, so the files other sessions
// are working in stay untouched:
//   Fighter.activeHits  -> per-fighter melee reach levelling
//   Fighter.takeHit     -> repeat-shot knockback cap + hammer hit limit
//   Game.start          -> clears the per-match counters
//
// WHY REACH LEVELLING (measured, dev/reach_probe.js + dev/NOTES-moves.md):
//   Every fighter's jab already reaches an opponent whose model is touching it, but the spare room
//   ("slack") ran from +30 px on the stubby ones (PEPE, CASHCAT, SHIB, SPARK, WRENCH, SHROOM, WISP)
//   to +49 px on the sword fighters (RONIN, FRO, LOBSTER). That 19 px gap is what "X has no reach"
//   feels like. The table below is the multiplier that brings each fighter up to the same ~45 px of
//   slack. Nobody is reduced: every value is >= 1, and the long-reach fighters keep their edge
//   because their far edge is already past the target.
const BAL = {
  on() { return !!Game.sigs; },

  // melee reach multiplier per fighter id (1 = unchanged). Generated by dev/reach_probe.js and
  // verified by re-running it with the table on: slack lands at 43-49 px for all 46.
  REACH: {
    cashcat: 1.205, pepe: 1.195, shib: 1.161, spark: 1.16, shroom: 1.157, turbo: 1.151, gwei: 1.148,
    tyrant: 1.139, cheems: 1.138, hoodie: 1.136, wisp: 1.135, bling: 1.126, bogdanoff: 1.112,
    popcat: 1.11, doge: 1.109, wif: 1.107, moodeng: 1.107, wojak: 1.107, mystic: 1.107, bear: 1.096,
    clanker: 1.086, omen: 1.085, chop: 1.082, slam: 1.08, topg: 1.08, bull: 1.078, trump: 1.077,
    mochi: 1.077, kaiju: 1.075, sin: 1.068, sifu: 1.067, gigachad: 1.062, ember: 1.058, brett: 1.058,
    pengu: 1.057, ape: 1.055, fartcoin: 1.051, techno: 1.047, floki: 1.046, ginga: 1.046, bonk: 1.032,
    whale: 1.012, fro: 1.007,
  },

  // ---- ranged chain-stun cap ----
  // "you can just keep shooting bullets til the person falls off": every shot of the same kind that
  // lands on the same victim inside CHAIN_T frames is worth less, and once the stack is deep the
  // hitstun is cut too, so the victim always gets a frame to act instead of being walked off stage.
  CHAIN_T: 100,
  CHAIN: [1, 0.85, 0.72, 0.62, 0.54, 0.48],
  CHAIN_STUN: 0.55,
  SHOTS: new Set(['laser', 'pellet', 'bullet', 'snipe', 'tracer', 'rocket', 'arrow', 'spark']),

  // ---- weapons ----
  GUN: { mag: 4, cool: 14, reload: 46, ammo: 10 },   // laser gun in local play: 4 shots, then a reload
  HAMMER: { time: 300, hits: 5 },                    // 5 s of hammer and at most 5 connected swings

  // the laser gun's fire rate and magazine. Returns true when the shot is swallowed.
  gunLock(f, it) {
    if (!this.on()) return false;
    if (it.ammo > this.GUN.ammo) it.ammo = this.GUN.ammo;          // shorter magazine than the arena's 16
    if (it.reload > Game.frame) return true;                       // still racking the cell
    if (it.cool > Game.frame) return true;                         // fire rate
    it.cool = Game.frame + this.GUN.cool;
    it.shots = (it.shots || 0) + 1;
    if (it.shots >= this.GUN.mag) {
      it.shots = 0; it.reload = Game.frame + this.GUN.reload;
      Game.text(f.x, f.y - f.h - 14, 'RELOAD', '#9fe8ff', 0.9);
      Sfx.tone(180, 90, 0.07, 'square', 0.07);
    }
    return false;
  },

  // hammer: count the swings that actually connect and end it early once the limit is hit
  hammerHit(att) {
    if (!this.on() || !att || att.state !== 'hammer') return;
    att.hammerHits = (att.hammerHits || 0) + 1;
    if (att.hammerHits >= this.HAMMER.hits && att.hammerT > 24) {
      att.hammerT = 24;
      Game.text(att.x, att.y - att.h - 16, 'HAMMER OUT', '#ffd45c', 1.1);
    }
  },

  // knockback/damage scaling for repeated shots of the same kind on the same victim
  shotScale(v, hb, att) {
    if (!this.on() || !hb || !hb.kind || !this.SHOTS.has(hb.kind)) return 1;
    const s = v.shotStack && v.shotStack.kind === hb.kind && Game.frame - v.shotStack.t < this.CHAIN_T
      ? v.shotStack : (v.shotStack = { kind: hb.kind, n: 0, t: Game.frame });
    s.t = Game.frame; s.n++;
    return this.CHAIN[Math.min(s.n - 1, this.CHAIN.length - 1)];
  },
  chainDeep(v) { return this.on() && v.shotStack && v.shotStack.n >= 3; },
};

// ===== status effects: burn and stagger =====
// Used by SPARK's bolts and KAIJU's fire breath (21_roster2.js moves2, local matches only). Ticks are
// fixed numbers on fixed frames - no RNG in the damage itself - and the whole thing only runs while
// BAL.on(), so seeded fights never see a burning fighter.
const STATUS = {
  BURN_EVERY: 10,          // a tick every 10 frames
  MAX: 150,
  burn(v, from, frames, dmg) {
    if (!BAL.on() || !v || v.state === 'dead') return;
    v.burnT = Math.min(this.MAX, Math.max(v.burnT || 0, frames));
    v.burnD = dmg || 1.1; v.burnBy = from || null;
  },
  // hex: a mark that goes off by itself later (MYSTIC, 67_unique.js)
  hex(v, from, frames) {
    if (!BAL.on() || !v || v.state === 'dead') return;
    v.hexT = frames || 180; v.hexBy = from || null;
  },
  // stagger: a short stun the victim cannot act out of, without the launch
  stagger(v, frames, color) {
    if (!BAL.on() || !v || v.state === 'dead' || v.untouchable) return;
    if (v.state === 'grabbed' || v.state === 'grabbing') return;
    v.move = null; v.setState('dizzy'); v.st = 150 - frames; v.vx *= 0.3; v.flashT = 8;
    Game.ring(v.x, v.y - v.h * 0.6, color || '#ffe84a', 60);
  },
  update() {
    if (!BAL.on() || Game.state !== 'match') return;
    if (this.lastF === Game.frame) return;       // hitlag / slow-mo: only tick on real sim frames
    this.lastF = Game.frame;
    for (const v of Game.fighters) {
      if (v.hexT > 0 && v.state !== 'dead') {
        v.hexT--;
        if (v.hexT % 10 === 0) Game.parts.push({ x: v.x + rand(-v.w * 0.4, v.w * 0.4), y: v.y - rand(6, v.h), vx: 0, vy: rand(-1.4, -0.4), life: 22, max: 22, color: '#c9a6ff', size: rand(5, 9), g: 0, soft: true });
        if (v.hexT === 0) {                                      // the mark goes off
          v.takeHit({ dmg: 11, ang: 88, bkb: 44, kbg: 70, radial: true }, v.hexBy || null, 1, v.x, 1);
          Game.ring(v.x, v.y - v.h * 0.5, '#c9a6ff', 120); Game.shake(10); Game.flashT = Math.max(Game.flashT, 3);
          Game.text(v.x, v.y - v.h - 30, 'HEX', '#c9a6ff', 1.5); Sfx.hit(0.7);
        }
      }
      if (!v.burnT || v.state === 'dead') { v.burnT = 0; continue; }
      v.burnT--;
      if (v.burnT % this.BURN_EVERY === 0) {
        const tr = (typeof TRAIT !== 'undefined' && TRAIT[v.c.id]) || null;
        const d = (v.burnD || 1.1) * (tr && tr.burn ? tr.burn : 1);
        v.dmg = Math.min(999, v.dmg + d); v.stats.taken += d;
        if (v.burnBy && v.burnBy !== v) v.burnBy.stats.dealt += d;
        v.flashT = Math.max(v.flashT, 3);
        Sfx.tone(220 + (v.burnT % 3) * 60, 60, 0.05, 'sawtooth', 0.04);
      }
      if (v.burnT % 3 === 0) Game.parts.push({ x: v.x + rand(-v.w * 0.4, v.w * 0.4), y: v.y - rand(4, v.h), vx: rand(-0.8, 0.8), vy: rand(-3.2, -1.2), life: 18, max: 18, color: v.burnT % 6 ? '#ff8a2a' : '#ffd45c', size: rand(6, 12), g: 0, fire: true });
    }
  },
};

// ---- install: reach levelling ----
(function () {
  const hits0 = Fighter.prototype.activeHits;
  Fighter.prototype.activeHits = function () {
    const out = hits0.call(this);
    if (!BAL.on() || !out.length) return out;
    const m = BAL.REACH[this.c.id];
    if (!m || m === 1) return out;
    for (const h of out) { h.x = this.x + (h.x - this.x) * m; h.r *= m; }
    return out;
  };

  // ---- install: repeat-shot cap + hammer limit ----
  const take0 = Fighter.prototype.takeHit;
  Fighter.prototype.takeHit = function (hb, att, mult, srcX, srcFace) {
    if (BAL.on()) {
      const k = BAL.shotScale(this, hb, att);
      if (k !== 1) mult = (mult || 1) * k;
      BAL.hammerHit(att);
    }
    const kb = take0.call(this, hb, att, mult, srcX, srcFace);
    // deep in a chain of the same shot, cut the hitstun so the victim is never walked off the stage
    if (BAL.chainDeep(this) && this.hitstun > 6) this.hitstun = Math.max(6, Math.floor(this.hitstun * BAL.CHAIN_STUN));
    // KO POWER (9/22). Measured on the owner's own online match: the opponent sat above 100% for 31
    // hits and was moved a median of ~4 units by each, so nobody could be knocked out and a 3-stock
    // match ran the full 7 minutes to time. "When it attacks nothing moves, the other person just
    // gets damage." The knockback formula already grows with damage, but not enough to match the
    // moves players actually use. So in normal play a hit on a badly damaged fighter launches harder,
    // ramping from nothing at 80% to 1.8x by 176%, so ordinary-damage play is exactly as it was - the "they're at 150, one clean hit sends them"
    // feeling Smash is built on. Armour and power-mode absorption are untouched (they return early
    // inside takeHit and leave velocity alone), and the seeded bet arena never runs this.
    if (BAL.on() && Game.combos && kb > 0 && (this.state === 'hitstun')) {
      const p = this.dmg || 0;
      const boost = Math.min(1.8, 1 + Math.max(0, p - 80) / 120);   // 1.0 at 80%, 1.5 at 140%, 1.8 by 176%
      if (boost > 1) {
        this.vx *= boost; this.vy *= boost;
        this.hitstun = Math.floor(this.hitstun * (1 + (boost - 1) * 0.5));
        if (dhypot(this.vx, this.vy) > 8.4) this.tumble = true;   // a real launch tumbles, as in takeHit
        // dhypot, not Math.hypot: Math.hypot's accuracy is implementation-defined, and this
        // decides tumble state, which changes what recovery options the fighter has.
      }
    }
    return kb;
  };

  // ---- install: per-match reset ----
  const start0 = Game.start;
  Game.start = function (slots, stageId, stocks, demo, itemsOn, seed) {
    const r = start0.call(this, slots, stageId, stocks, demo, itemsOn, seed);
    for (const f of this.fighters) { f.shotStack = null; f.hammerHits = 0; f.burnT = 0; f.hexT = 0; }
    return r;
  };

  // ---- install: status ticks (burn) ----
  const step0 = Game.step;
  Game.step = function () { const r = step0.call(this); STATUS.update(); return r; };
})();
