// Builds net/engine/sim.js: the page's fight code (the same SIM_FILES list build.py uses for
// arena/fightsim.js) plus the online lockstep driver src/63_netsim.js. The game server loads it into
// one sandboxed context per match and replays every match with it.
//
//   node tools/build-engine.js [--check]
//
// Run it after every `python3 build.py`, and deploy engine/ together with index.html (see README).
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..', '..');
const src = path.join(root, 'src');
const buildPy = fs.readFileSync(path.join(root, 'build.py'), 'utf8');
const m = buildPy.match(/SIM_FILES\s*=\s*\[([^\]]*)\]/);
if (!m) throw new Error('SIM_FILES not found in build.py');
const files = [...m[1].matchAll(/'([^']+)'/g)].map(x => x[1]);
// fighter data added in new 2x_ files must reach the server too, even if build.py's list lags behind
for (const f of fs.readdirSync(src).sort()) {
  if (/^2\d_.*\.js$/.test(f) && !files.includes(f) && f !== '30_draw.js') {
    console.warn('note: ' + f + ' is not in build.py SIM_FILES; including it in the online engine');
    files.splice(files.findIndex(x => x > f) === -1 ? files.length : files.findIndex(x => x > f), 0, f);
  }
}
// the online driver sits at its sorted place, exactly as in the page (it snapshots the fight functions
// when it loads, so everything before it must match the page's order)
if (!files.includes('63_netsim.js')) files.splice(files.findIndex(x => x > '63_netsim.js') === -1 ? files.length : files.findIndex(x => x > '63_netsim.js'), 0, '63_netsim.js');

const prelude = `// GENERATED by net/tools/build-engine.js from src/ -- the page's fight code + the online driver.
var addEventListener = function () {};
var R = { w: 1280, h: 720 };
var UI = { startDemo() {}, showResults() {}, onPause() {} };
`;
const texts = files.map(f => fs.readFileSync(path.join(src, f), 'utf8'));
// page and engine must come from the same sources: every sim file must appear verbatim in the built page
let page = '';
try { page = fs.readFileSync(path.join(root, 'index.html'), 'utf8'); } catch (e) { /* no page built yet */ }
const stale = files.filter((f, i) => !page.includes(texts[i]));
if (stale.length) {
  console.error('note: src/ changed since index.html was built (' + stale.join(', ') + ')');
}
const body = files.map((f, i) => '// ---- ' + f + '\n' + texts[i]).join('\n');
let code = prelude + body + '\n';
// Preferred source: arena/fightsim.js, which build.py writes in the same run as index.html (its SIM_FILES
// include 63_netsim.js). That engine always matches the page that was built with it.
const arenaSim = path.join(root, 'arena', 'fightsim.js');
let fromBuild = false;
try {
  const fs2 = fs.readFileSync(arenaSim, 'utf8');
  if (fs2.includes('class NetLockstep') && fs2.includes('const NetSim')) { code = fs2 + '\n'; fromBuild = true; }
} catch (e) { /* no build yet */ }
if (fromBuild) console.log('engine source: arena/fightsim.js (same build.py run as index.html)');
else if (stale.length && process.argv.includes('--strict')) process.exit(2);

// load it once the way the server does, and print the engine fingerprint
const ctx = vm.createContext({ console });
new vm.Script(code + '\n;globalThis.__sim = { NetSim, CHARS };', { filename: 'sim.js' }).runInContext(ctx);
const digest = ctx.__sim.NetSim.digest();
const chars = ctx.__sim.CHARS.map(c => c.id);

if (process.argv.includes('--check')) { console.log(JSON.stringify({ digest, chars: chars.length })); process.exit(0); }
const out = path.join(__dirname, '..', 'engine');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'sim.js'), code);
// one file per engine version: the server keeps serving pages from the previous build while a new one rolls out
fs.writeFileSync(path.join(out, 'sim-' + digest + '.js'), code);
const olds = fs.readdirSync(out).filter(f => /^sim-v\d+-[0-9a-f]+\.js$/.test(f)).map(f => ({ f, t: fs.statSync(path.join(out, f)).mtimeMs })).sort((a, b) => b.t - a.t);
for (const o of olds.slice(12)) fs.unlinkSync(path.join(out, o.f));
fs.writeFileSync(path.join(__dirname, '..', 'engine', 'engine.json'), JSON.stringify({ digest, source: fromBuild ? 'arena/fightsim.js' : 'src', files, chars, built: new Date().toISOString() }, null, 1));
console.log('engine', digest, files.length + ' files', chars.length + ' fighters');
